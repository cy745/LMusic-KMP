package com.lalilu.lmedia.domain.source

/**
 * 调试用：媒体源丢掉自己的本地缓存，回到「这首歌从没被加载过」的样子。
 *
 * 为什么需要这个接口：像「切歌瞬间封面闪一下底色」「时长还没到所以进度条空一段」这类问题，
 * 前提条件都是**这首歌的元数据/封面还没落盘**——而一旦跑过一次，缓存就在那儿了，人手工
 * 点不出来。调试通道只认识 [MediaSource] 这个抽象，缓存却是各来源自己的事（本地文件源根本没有
 * 缓存），所以用一个可选能力接口表达，而不是在调试通道里 `is WebDavSource` 硬判断。
 *
 * 不实现这个接口 = 这个来源没有可清的本地缓存。
 */
interface MediaCacheDebugControl {

    /**
     * 丢掉本地缓存。
     *
     * [audioId] 为 null 表示整个来源（音频分段、提取记录、封面与边车全部清空）；给具体 id 时
     * 只清这一首。注意只清一首时**不要清正在播放的那首**：代理可能正从被删掉的分段上读字节。
     */
    suspend fun clearLocalCache(audioId: String? = null)
}
